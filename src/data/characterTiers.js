/**
 * 모든 등수(1위, 2위, 3위 ... 100위 ...)마다 100% 다른 고유한 캐릭터 티어 객체 반환
 * @param {number} rank 1부터 시작하는 순위
 * @param {number} totalCount 전체 학생 수
 * @returns {object} 순위 고유의 티어 정보
 */
export function getCharacterTierByRank(rank, totalCount = 20) {
  const safeRank = Math.max(1, parseInt(rank) || 1);
  const percentage = ((safeRank / Math.max(totalCount, 1)) * 100).toFixed(1);

  // 1. 1위~25위까지 수제작 고유 테마 매칭
  if (safeRank <= RANK_CUSTOM_THEMES.length) {
    const theme = RANK_CUSTOM_THEMES[safeRank - 1];
    return {
      tier: safeRank,
      rank: safeRank,
      calculatedPercent: percentage,
      ...theme,
    };
  }

  // 2. 26위 이상: 결정론적 고유 캐릭터 생성기 (Unique Procedural Rank Generator)
  const adjIndex = (safeRank * 7) % ADJECTIVES.length;
  const nounIndex = (safeRank * 13) % NOUNS.length;
  const adj = ADJECTIVES[adjIndex];
  const noun = NOUNS[nounIndex];

  const title = `${adj} ${noun.name}`;
  const emoji = noun.emoji;

  const bgColors = [
    ['#FFF1F2', '#FFE4E6', '#FECDD3'],
    ['#F5F3FF', '#EDE9FE', '#DDD6FE'],
    ['#EEF2FF', '#E0E7FF', '#C7D2FE'],
    ['#ECFDF5', '#D1FAE5', '#A7F3D0'],
    ['#FFFBEB', '#FEF3C7', '#FDE68A'],
    ['#F0F9FF', '#E0F2FE', '#BAE6FD'],
  ];
  const bgGrad = bgColors[safeRank % bgColors.length];

  return {
    tier: safeRank,
    rank: safeRank,
    calculatedPercent: percentage,
    title: title,
    emoji: emoji,
    badgeBg: 'bg-gradient-to-r from-pink-400 via-purple-400 to-indigo-400 text-white shadow-xs',
    cardBorder: 'border-pink-200',
    hairColor: noun.color,
    bgGrad: bgGrad,
    prop: noun.prop,
    accessory: `${safeRank}위 고유 칭호`,
    description: `${safeRank}위의 독보적인 매력 발산 중! 다음 랭킹 상승을 향해 열공 질주 중인 멋진 학생!`,
    quote: `“${safeRank}위라는 건 언제든 상위권으로 치고 올라갈 수 있다는 뜻!”`,
    reward: `✨ ${safeRank}위 응원: 힘내라 갓생 에너지 간식 선물`,
  };
}

